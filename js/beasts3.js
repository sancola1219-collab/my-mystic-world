function stageBaseLevel(k) { return k <= 6 ? 58 + k * 2 : k <= 18 ? 70 + (k - 6) * 2 : 70 + (k - 18) * 2; }

const FAMILY_ROSTER = {}; // 關卡 → 幻靈編號（依階段）
(function buildBeasts() {
  let id = 101;
  const total = { 1: 320, 2: 430, 3: 545, 4: 660 };
  const addBeast = (name, types, stage, role, sig, desc, art, hab) => {
    const b = ROLE_W[role].map(x => Math.round(total[stage] * x));
    if (art.final) b.forEach((v, i) => b[i] = Math.round(v * 1.12));
    const sigId = 'sig' + id;
    MOVES[sigId] = { n: sig, t: types[0], p: { 1: 80, 2: 100, 3: 120, 4: 140 }[stage], a: 95, pp: 8, ult: stage >= 3 ? 1 : 0, d: `${name}的招牌招式。` };
    const [t1, t2] = types, M1 = TYPE_MOVES[t1], M2 = TYPE_MOVES[t2 || t1];
    MONS[id] = {
      n: name, t: types, b, cr: stage === 4 ? 12 : stage === 3 ? 45 : stage === 2 ? 90 : 170, xp: { 1: 100, 2: 170, 3: 250, 4: 330 }[stage],
      h: (0.6 + stage * 0.7 + (id % 7) * 0.2).toFixed(1) + ' m', w: (8 + stage * stage * 14 + (id % 11) * 2.3).toFixed(1) + ' kg',
      hab, desc, big: stage === 4,
      learn: [[1, M1[0][0]], [20, M1[3][0]], [35, M2[0][0]], [45, M1[1][0]], [52, M2[1][0]], [58, sigId], [62, M1[2][0]], [70, M2[2][0]], [78, ULT[t1][0]]],
      art,
    };
    const me = id;
    SPRITES[me] = (c, t) => drawPlan(c, me, t);
    return id++;
  };
  for (const [plan, types, a, b, c, opts, names, sig, desc, role, k] of FAMILIES) {
    const L = stageBaseLevel(k);
    const roster = FAMILY_ROSTER[k] = FAMILY_ROSTER[k] || [];
    const line = [];
    names.forEach((n, i) => {
      const stage = names.length === 2 ? i + 2 : i + 1;
      const art = Object.assign({ plan, a, b, c, s: stage }, opts);
      if (opts.headsByStage) art.heads = stage;
      if (art.pat === 1) art.pat = 'star';
      const stageNote = stage === 1 ? '幼體。' : stage === 2 ? '成長後力量大增。' : '最終形態，擁有壓倒性的力量。';
      const mid = addBeast(n, types, stage, role, sig, desc + stageNote, art, '');
      line.push(mid); roster.push([mid, stage]);
    });
    line.forEach((mid, i) => { if (line[i + 1]) MONS[mid].evo = { lv: Math.min(98, L + 4 + i * 6), to: line[i + 1] }; });
  }
  for (const [plan, types, a, b, c, opts, name, sig, desc, role, k] of LEGEND_BEASTS) {
    const art = Object.assign({ plan, a, b, c, s: 4 }, opts);
    if (k === 18 || k === 30) art.final = 1;
    const mid = addBeast(name, types, 4, role, sig, desc, art, '');
    (FAMILY_ROSTER['L'] = FAMILY_ROSTER['L'] || {})[k] = mid;
  }
  if (id !== 301) console.error('幻靈數量不對', id - 1);
})();

