// 小圖快取：清單裡不用每一幀重畫複雜的造型
const drawMonLive = drawMon;
const MON_CACHE = {};
drawMon = function (cx, id, x, y, size, t, opt = {}) {
  if (!(opt.still && MONS[id] && MONS[id].art && size <= 130 && !opt.flip)) return drawMonLive(cx, id, x, y, size, t, opt);
  const key = id + '_' + size;
  let cv = MON_CACHE[key];
  if (!cv) {
    cv = MON_CACHE[key] = document.createElement('canvas'); cv.width = cv.height = size * 2 * SS;
    const q = cv.getContext('2d'); q.scale(SS, SS); drawMonLive(q, id, size, size, size, 1.2, { still: true });
  }
  cx.save(); if (opt.alpha != null) cx.globalAlpha = opt.alpha;
  cx.drawImage(cv, x - size, y - size, size * 2, size * 2); cx.restore();
};
